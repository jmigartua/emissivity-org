"""
generate_network.py — single source of truth: _data/institutions.yml

Emits:
  assets/data/labs.json     (map markers + stats; consumed by labs-map.js)
  network/index.qmd         (directory page: map + tier-grouped table)
  network/<id>.qmd          (profiles migrated from the legacy ecosystem,
                             wrapped in the v3 article layout — only when a
                             legacy source exists and no hand-written profile
                             is marked KEEP)

Coordinates live here for now (TODO: fold lat/lon into institutions.yml).
"""
